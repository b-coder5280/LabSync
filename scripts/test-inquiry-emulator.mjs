async function tokenFor(adminClaim) {
  const email = `${crypto.randomUUID()}@example.invalid`, password = 'EmulatorOnlyPassword42!';
  const user = await auth.createUser({ email, password });
  if(adminClaim) await auth.setCustomUserClaims(user.uid, { admin: true });
  const response = await fetch('http://127.0.0.1:9095/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=emulator-only', { method: 'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ email,password,returnSecureToken:true }) });
  return (await response.json()).idToken;
}
